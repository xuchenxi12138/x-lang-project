// semver.h — 语义化版本与版本约束
//
// ── 为什么版本要单独一个文件 ────────────────────────────────
//
// 版本比较是包管理里唯一**没有 I/O、没有全局状态、没有诊断打印**
// 的部分。它纯粹是「两个字符串谁是新的」。正因为纯，它可以被
// 完整地测：几十条断言覆盖边界，跑起来是毫秒级。
//
// 而依赖解析不是 —— 解析要读目录、读清单、处理冲突。把它和版本
// 比较混在一起，测试就得先造一堆目录，于是没人愿意写测试，于是
// 「^0.0.3 到底该匹配到哪」这种真会出错的地方就没人验证。
//
// 拆开之后，解析层可以信任 sem_satisfies 是对的，只专心处理
// 「多个约束求交集」和「循环依赖」这些解析自身的难点。
//
// ── 支持哪些约束语法 ────────────────────────────────────────
//
//   1.2.3        等价于 ^1.2.3（Cargo / npm 的默认语义）
//   =1.2.3       精确
//   ^1.2.3       >=1.2.3 <2.0.0（第一个非零位允许变）
//   ~1.2.3       >=1.2.3 <1.3.0（只允许 patch 变）
//   >=1.2.0      大于等于
//   >1.2.0       大于
//   <=2.0.0      小于等于
//   <2.0.0       小于
//   *            任意
//
// ── 为什么默认是 ^ 而不是 = ─────────────────────────────────
//
// 大多数人在 x.toml 里写 `jsonx = "1.2"` 时想表达的是「1.x 里
// 任何能用的版本」，不是「必须正好 1.2.0」。写成 `=` 会让每次
// 上游发补丁版都得改清单，实际结果是所有人长期钉在旧版本上。
//
// 想要精确就显式写 `=1.2.3`。默认宽松、要严就明说 —— 这条规则
// 在 lock 文件上还有第二道保险：真正参与构建的版本永远是 lock 里
// 那个确定的版本，清单里的范围只用来决定「哪些版本可以接受」。
//
// ── 预发布版本的处理 ────────────────────────────────────────
//
// 1.0.0-alpha 小于 1.0.0。并且：**约束里没写预发布标识时，不匹配
// 任何预发布版本**。所以 `^1.2.0` 不会因为注册表里有个 2.0.0-beta
// 就选它，也不会选 1.3.0-rc1。
//
// 这条规则看着啰嗦，但它挡住的是真实事故：预发布版本通常是
// 作者半夜推的、没跑完整测试的版本。默认不选，是让「升级」这件
// 事可预测。

#ifndef X_SEMVER_H
#define X_SEMVER_H

#include <stdbool.h>
#include <stddef.h>

// 一个具体版本：1.2.3-rc1
typedef struct {
    int  major;
    int  minor;
    int  patch;
    // 预发布标识。空串表示正式版。
    //
    // 长度上限 63：semver 规范对标识长度没有硬限制，但版本号是要
    // 出现在命令行输出、lock 文件、错误信息里的东西。允许无限长只是
    // 把「一个畸形的版本号能把整份诊断挤爆」这个可能性留着。真需要
    // 更长的标识，说明该换版本方案了，不是该加长这个字段。
    char pre[64];
} SemVer;

// 约束的运算符。
//
// ── 为什么带 SV_ 前缀 ───────────────────────────────────────
//
// 第一版叫 OP_EXACT / OP_GE / OP_LT…，与 x.h 里比较运算符的枚举
// （OP_EQ / OP_NE / OP_LT / OP_LE / OP_GT / OP_GE）直接撞名。
// 两个枚举在同一编译单元里展开时，后到的那个是重定义 —— C 的枚举
// 没有作用域。
//
// 加前缀不只是绕过编译错误的权宜之计：`OP_LT` 在 x.h 里是
// 「表达式 `a < b` 的运算符」，在这里是「版本约束 `<2.0.0`」。
// 两件事在语义上毫无关系，用同一个名字本身就是错的。
typedef enum {
    SV_ANY = 0,     // *
    SV_EXACT,       // =1.2.3
    SV_CARET,       // ^1.2.3（也是裸版本号的默认语义）
    SV_TILDE,       // ~1.2.3
    SV_GE,          // >=1.2.0
    SV_GT,          // >1.2.0
    SV_LE,          // <=2.0.0
    SV_LT,          // <2.0.0
} SemOp;

typedef struct {
    SemOp   op;
    SemVer  ver;
    // 约束里写了几段数字（1 / 2 / 3）。
    //
    // 这个字段不是为了好看，而是 ^ 和 ~ 的上界算不出来就靠它：
    //
    //   ~1      → >=1.0.0 <2.0.0     （parts=1，升 major）
    //   ~1.2    → >=1.2.0 <1.3.0     （parts=2，升 minor）
    //   ^0      → >=0.0.0 <1.0.0     （parts=1）
    //   ^0.0    → >=0.0.0 <0.1.0     （parts=2）
    //   ^0.0.3  → >=0.0.3 <0.0.4     （parts=3，patch 很小所以只放 patch）
    //
    // 只按 major/minor/patch 的数值判断会算错 ^0 和 ^0.0 —— 它们的
    // 三个数字全是 0，光看数值无法区分「用户写了 1 段」还是「写了 3 段」。
    int     parts;
    // 原始文本，只用于诊断（"版本 1.2 不满足约束 ^2.0"）。
    //
    // 为什么不重新格式化：用户写的可能是 `>= 1.2.0`（带空格）或
    // `v1.2.3`。回显他写的那一串，比回显一个我们重新拼的字符串
    // 更容易对上号。
    char    raw[64];
} SemReq;

// 解析版本号 `1.2.3` / `1.2` / `1` / `1.2.3-rc1` / `v1.2.3`。
// 缺的部件补 0。失败返回 false。
bool sem_parse(const char* s, SemVer* out);

// 比较两个版本：a<b 返回负，相等返回 0，a>b 返回正。
int  sem_cmp(const SemVer* a, const SemVer* b);

// 解析版本约束。失败返回 false。
//
// 空串与 "*" 都解析成 OP_ANY —— 空串当成「任何版本」比当成错误
// 更合适：清单里 `dep = ""` 大概率是用户想写个占位，编译时不该
// 因为一个还没填的字段就整体失败。
bool sem_parse_req(const char* s, SemReq* out);

// 版本 v 是否满足约束 r。
bool sem_satisfies(const SemVer* v, const SemReq* r);

// 格式化成 `1.2.3` / `1.2.3-rc1`。out 至少 96 字节。
void sem_format(const SemVer* v, char* out, size_t n);

// 把约束还原成人能读的形式，用于诊断。out 至少 96 字节。
void sem_format_req(const SemReq* r, char* out, size_t n);

#endif // X_SEMVER_H