// profile.h — 使用场景（Profile）：一种数据链路，一个运行时入口
//
// ── 这个文件解决的是哪个问题 ────────────────────────────────
//
// 用户原话：「既然这个语言是跨语种跨平台的，为了不让运行程序浪费太多
// 时间在平台、接口、协议的调用上，我们一种使用场景写一个执行程序入口。」
//
// 换成工程语言：**平台适配的代价不该在运行期支付**。一个只在控制台
// 打印的程序，不该带着 GDI 的字体缓存、双缓冲位图、消息泵进来；一个
// 桌面程序也不该在启动时去探测 stdin 是不是终端。
//
// 传统做法是「一个运行时 + 一堆运行时开关」：链接进来，用 if 判断，
// 用函数指针派发。这条路的问题是所有代价都在，只是被 if 藏起来了 ——
// 二进制的体积、进程启动时重定位的页数、链接进来的库依赖，一样不少。
//
// 这里的做法是**在编译期把链路切开**：每个 Profile 是一套固定装配，
// 编译时就知道「要不要窗口代码」「要不要控制台路径」「栈开多大」
// 「链哪几个库」。运行期的派发层次降到零 —— 因为只有一条路，没有
// 第二条可选。
//
//   ★ 场景在执行之前定死，不在执行之中判断。
//
// ── 三个档位与它们的真实差别 ────────────────────────────────
//
// 只有三档，不是文件里那种七档（spec/02 §10 的完整设计）。理由很直接：
// **能真实产出并跑起来的档位才有资格进表**。多列一档就是多一个「声称
// 支持但没测过」的条目，用户按表操作、拿到跑不了的产物，从此不信文档。
//
//   console（默认）  控制台。无窗口代码、无窗口库、main() 直出。
//   desktop          桌面 GUI。内嵌窗口运行时、链 gdi32/user32、
//                    用 WINDOWS 子系统（双击不弹黑框）、栈开大。
//   service          长驻服务。与 console 只差一条：stdout 无缓冲，
//                    进程被杀时已输出的内容留在日志里。
//
// ── 为什么会「浪费」在平台调用上：一个具体的例子 ────────────
//
// Windows 的 PE 头里有个 Subsystem 字段。值为 3（CONSOLE）时，进程
// 启动时系统给你挂一个控制台窗口；值为 2（WINDOWS_GUI）时不给。
// 这件事**没法在运行期决定**——它写在文件头里，由加载器读。
//
// 所以一个双击运行、不该有黑框的桌面程序，必须编成 subsystem=2。
// 而 subsystem=2 的 PE 期望入口是 WinMain，不是 main。这两件事
// 是链接期的事，运行期没有任何办法补救——这正是「场景化入口」的
// 物理基础，不是我们发明的规则。
//
// 处理办法见 codegen_c.c 里 gen_entry 的注释：仍写 main()，但通过
// `-Wl,--subsystem,windows -Wl,--entry=mainCRTStartup` 直接指定
// 入口符号。这样同一份函数体在两种子系统下都能用，不必写 WinMain，
// 也就不用为了拿命令行参数去调 GetCommandLineW + 自己切分。

#ifndef X_PROFILE_H
#define X_PROFILE_H

#include <stdbool.h>
#include <stdio.h>

// ============================================================
// 档位
// ============================================================

typedef enum {
    PROF_CONSOLE = 0,   // 控制台（默认）
    PROF_DESKTOP,       // 桌面 GUI
    PROF_SERVICE,       // 长驻服务
    PROF_COUNT
} XProfile;

// stdout 的缓冲策略。
//
// 这是三档里唯一在**运行期**生效的差异 —— 其余（子系统、链接层、
// 栈容量）全在编译期定死。之所以留一个运行期的，是因为它表达的是
// 「进程被杀时输出能留住多少」这件事，而这件事只可能在进程死亡时
// 被观察到，没有编译期的等价物。
typedef enum {
    XBUF_LINE = 0,   // 行缓冲（_IOLBF）：见到 \n 才写出去
    XBUF_NONE,       // 无缓冲（_IONBF）：每次输出立即写出去
} XStdoutBuf;

// 一个档位的完整装配。
//
// 全部是**编译期常量**：没有一项需要在运行期查。这张表就是
// 「场景 = 固定链路」这句话的落地形式。
//
// ── 为什么只有这五个字段 ────────────────────────────────────
//
// 这里原本还有 need_stdout 与 allow_bin_depend 两个「语义约束」
// 字段，注释写着「现在写下来，是为了将来有地方挂」。它们从头到尾
// 没有任何代码读过 —— 一个存进结构体、从来没有读者的字段，
// 与不存在没有区别，唯一的实际作用是让读者以为系统管了这件事。
//
// 所以删掉。真要加约束，等有代码能执行它的时候再加，并且**同时**
// 加一条能证伪它的测试。
typedef struct {
    const char* name;        // 命令行里的名字，"console" / "desktop" / "service"
    const char* label;       // 中文名，用于 --profile list 与诊断
    const char* purpose;     // 一行用途，进表

    // ── 链接层 ──
    bool want_gui;           // 是否内嵌窗口运行时（并链 gdi32/user32）
    bool gui_subsystem;      // 是否要求 WINDOWS 子系统（PE）；其他平台忽略

    // ── 入口层 ──
    //
    // 栈容量按「单帧局部变量数 × 深度上限」算，深度就是这里。
    // 桌面档开得更大：GUI 程序的调用栈天生更深（消息泵 → 事件派发
    // → 业务回调 → 重绘），而且桌面程序崩一次就是用户看得见的白窗口。
    int  call_depth;

    // ── 输出层 ──
    XStdoutBuf stdout_buf;
} XProfileDef;

// 按名字查档位。查不到返回 NULL，**不做模糊匹配** —— 与 --target 同理，
// 猜错档位的代价是编出一个「能跑但不对」的产物（比如桌面程序带着黑框）。
const XProfileDef* profile_find(const char* name);

// 按枚举取定义（越界返回 NULL）
const XProfileDef* profile_get(XProfile p);

// 默认档位名（"console"）
const char* profile_default_name(void);

// 打印档位表（x profile list）
void profile_print_table(FILE* out);

// 名字是否合法。用于参数解析的早期校验 —— 在读完整个命令行之前
// 就报错，比等到 build 里再报有用（用户能立刻看到拼错在哪）。
bool profile_name_ok(const char* name);

#endif // X_PROFILE_H