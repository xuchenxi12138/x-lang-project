/* ============================================================
 * entry.s —— 内核镜像的第一个字节
 * ============================================================
 *
 * ── 为什么需要这个桩，而不是让 _start 当第一段 ────────────
 *
 * 引导扇区跳到物理地址 0x10000，那里必须是「能立即执行的
 * 第一条指令」。而 GCC 生成的函数能不能排在 0x10000，取决于：
 *
 *   · 段名（MinGW 下每个函数一个 .text$函数名）
 *   · 链接脚本的段选择通配是否与 binutils 的 $ 处理一致
 *   · --gc-sections 之后哪些段留下
 *
 * 这三件事任何一个变动，入口就会漂到别处 —— 而症状是「跳到
 * 0x10000 就崩」，崩溃地址看起来与代码毫无关系。
 *
 * 用一个**独立的本文件**当第一段，把这个不确定性彻底消除：
 * 段名由我们自己控制（.text.entry），链接脚本把它放在最前面，
 * 它就一定在 0x10000。
 *
 * 这与 Linux 的 arch/x86/boot/header.S、GRUB 的 start.S 是
 * 同一个思路：入口点不能依赖编译器的布局策略。
 *
 * ── 清零为什么必须在这里做，不能省 ────────────────────────
 *
 * 值栈（786 KB 的 static V s[49152]）在 PE 里**是**占文件的 ——
 * PE 没有 SHT_NOBITS，全零数据照写。但本镜像的 .vstack 段
 * 刻意不导出（见 kernel.ld 的注释），所以引导时那 786 KB 的
 * 物理内存里是什么完全不确定：可能是 QEMU 留的垃圾，可能是
 * 上一轮运行的残留。
 *
 * 若不清零，值栈里的 V 结构 t 字段是随机值，第一次 v_rel 就会
 * 按随机的类型标签去操作指针，随机崩溃 —— 而且崩的位置随机，
 * 看起来像「内核本身有 bug」而不是「少了一次初始化」。
 *
 * 只清 t 字段不够：V 里有 s/a/o 联合体（指针或 double），
 * GC 与引用计数会读它们。清零整块最便宜（rep stosl 约 786 KB /
 * 4 = 19.6 万次迭代，几十毫秒），也彻底消除这一整类问题。
 */

.code32
.section .text.entry, "ax"
.global _entry
_entry:
    /* ── 清零值栈 ───────────────────────────────────────────
     * 用链接脚本提供的 __vstack_start / __vstack_end。
     *
     * rep stosd 一次写 4 字节，比 rep stosb 快 4 倍。
     * 前提是地址与长度都是 4 字节对齐 —— ecx 取 /4 的商，
     * 余下的 0~3 字节由 stosb 收尾。链接脚本里有 ALIGN(4)，
     * 起始地址必然对齐；长度是 786432 = 4 × 196608，也必然对齐，
     * 但保留余数处理是为了「值栈大小将来变了也不出错」。 */
    movl    $__vstack_start, %edi
    movl    $__vstack_end, %ecx
    subl    %edi, %ecx
    jz      .bss_done               /* 空值栈直接跳过 */
    xorl    %eax, %eax
    movl    %ecx, %edx
    shrl    $2, %ecx
    rep     stosl                   /* 4 字节为单位清零（AT&T 里叫 stosl） */
    movl    %edx, %ecx
    andl    $3, %ecx
    rep     stosb                   /* 收尾余数 */
.bss_done:

    /* 此时 boot.s 已经建好平坦的 32 位环境与栈。
     * 跳到 X 编译出来的 _start（GCC 在 MinGW 下给它加一个
     * 前导下划线，所以符号是 __start）。
     *
     * 用 jmp 而不是 call：_start 末尾是死循环，永不返回。 */
    jmp     __start

/* 万一 __start 返回（不该发生），停住而不是跑飞 */
.halt_forever:
    cli
    hlt
    jmp     .halt_forever